#!/bin/bash
###############################################################################
# Dataset Configuration Script
#
# This script configures dataset paths for C++ experiments.
# It updates experiments/src/dataset_config.hpp with the correct paths
# based on the project location.
#
# Usage:
#   ./configure_datasets.sh                    # Auto-detect paths
#   ./configure_datasets.sh --legacy-path PATH # Set legacy dataset path
#   ./configure_datasets.sh --help             # Show help
###############################################################################

set -e

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

show_help() {
    cat <<EOF

Dataset Configuration Script
============================

This script configures dataset paths for C++ experiments by updating
experiments/src/dataset_config.hpp with the correct absolute paths.

Usage:
  ./configure_datasets.sh [OPTIONS]

Options:
  --help                Show this help message

Examples:
  # Auto-detect project paths
  ./configure_datasets.sh

What this script does:
  1. Detects the project root directory
  2. Sets DATASETS_BASE_PATH to <project>/datasets
  3. Sets EXPERIMENTS_OUTPUT_PATH to <project>/experiments/output
  4. Updates experiments/src/dataset_config.hpp
  5. Creates output directories if needed

EOF
}

###############################################################################
# Parse Arguments
###############################################################################

while [[ $# -gt 0 ]]; do
    case $1 in
        --help|-h)
            show_help
            exit 0
            ;;
        *)
            log_error "Unknown option: $1"
            show_help
            exit 1
            ;;
    esac
done

###############################################################################
# Detect Paths
###############################################################################

# Get the absolute path to the project root
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

DATASETS_PATH="$PROJECT_ROOT/datasets"
EXPERIMENTS_OUTPUT_PATH="$PROJECT_ROOT/experiments/output"
CONFIG_FILE="$PROJECT_ROOT/experiments/src/dataset_config.hpp"

log_info "Configuring dataset paths..."
echo ""
echo "Project root:        $PROJECT_ROOT"
echo "Datasets directory:  $DATASETS_PATH"
echo "Experiments output:  $EXPERIMENTS_OUTPUT_PATH"
echo ""

###############################################################################
# Create Directories
###############################################################################

log_info "Creating directories..."

mkdir -p "$DATASETS_PATH"
mkdir -p "$EXPERIMENTS_OUTPUT_PATH"
mkdir -p "$DATASETS_PATH/shapefiles"
mkdir -p "$DATASETS_PATH/hdf5"

log_success "Directories created"

###############################################################################
# Generate dataset_config.hpp
###############################################################################

log_info "Generating dataset_config.hpp..."

cat > "$CONFIG_FILE" <<EOF
/**
 * @file dataset_config.hpp
 * @brief Central configuration for dataset paths and experiment output
 *
 * This file contains all dataset paths and experiment configuration.
 * It is automatically generated by configure_datasets.sh
 *
 * DO NOT EDIT THIS FILE MANUALLY - use configure_datasets.sh instead
 *
 * Generated: $(date)
 * Project root: $PROJECT_ROOT
 */

#ifndef DATASET_CONFIG_HPP
#define DATASET_CONFIG_HPP

#include <string>
#include <vector>
#include <sys/stat.h>

namespace dataset_config {

// ============================================================================
// Base Paths
// ============================================================================

// Base directory for all datasets
const std::string DATASETS_BASE_PATH = "$DATASETS_PATH";

// Base directory for experiment outputs
const std::string EXPERIMENTS_OUTPUT_PATH = "$EXPERIMENTS_OUTPUT_PATH";

// ============================================================================
// Dataset Subdirectories
// ============================================================================

// COVID-19 datasets (downloaded via download_datasets.sh)
const std::string COVID19_PATH = DATASETS_BASE_PATH + "/covid19";

// GDELT datasets (downloaded via download_datasets.sh)
const std::string GDELT_PATH = DATASETS_BASE_PATH + "/gdelt";

// Infrastructure failure datasets (downloaded via download_datasets.sh)
const std::string INFRASTRUCTURE_PATH = DATASETS_BASE_PATH + "/infrastructure";

// Lightning strike datasets
const std::string LIGHTNING_PATH = DATASETS_BASE_PATH + "/lightning";

// Administrative boundaries (Natural Earth)
const std::string ADMIN_BOUNDARIES_PATH = DATASETS_BASE_PATH + "/admin_boundaries";

// Shapefile datasets directory
const std::string SHAPEFILES_PATH = DATASETS_BASE_PATH + "/shapefiles";

// HDF5 converted datasets
const std::string HDF5_PATH = DATASETS_BASE_PATH + "/hdf5";

// ============================================================================
// Specific Dataset Files
// ============================================================================

// COVID-19 files
const std::string COVID19_DAILY_REPORTS = COVID19_PATH + "/csse_covid_19_daily_reports";
const std::string COVID19_TIME_SERIES = COVID19_PATH + "/csse_covid_19_time_series";

// GDELT files
const std::string GDELT_EVENTS_CSV = GDELT_PATH + "/gdelt_events_sample.csv";
const std::string GDELT_EVENTS_HDF5 = HDF5_PATH + "/gdelt_events.h5";

// Infrastructure files
const std::string NYC_311_CSV = INFRASTRUCTURE_PATH + "/nyc_311_sample.csv";
const std::string NYC_311_HDF5 = HDF5_PATH + "/nyc_311.h5";

// Shapefile paths
const std::string US_ZCTA_SHAPEFILE = SHAPEFILES_PATH + "/tl_2017_us_zcta510/tl_2017_us_zcta510";
const std::string GLOBAL_LSIB_SHAPEFILE = SHAPEFILES_PATH + "/Global_LSIB_Polygons_Detailed/Global_LSIB_Polygons_Detailed";

// Natural Earth admin boundary shapefiles
const std::string NE_COUNTRIES_10M = ADMIN_BOUNDARIES_PATH + "/ne_10m_admin_0_countries/ne_10m_admin_0_countries";
const std::string NE_STATES_10M = ADMIN_BOUNDARIES_PATH + "/ne_10m_admin_1_states_provinces/ne_10m_admin_1_states_provinces";
const std::string NE_COUNTRIES_50M = ADMIN_BOUNDARIES_PATH + "/ne_50m_admin_0_countries/ne_50m_admin_0_countries";

// ============================================================================
// Dataset Lists
// ============================================================================

// Shapefile datasets (paths relative to SHAPEFILES_PATH or ADMIN_BOUNDARIES_PATH)
const std::vector<std::string> POLYGON_DATASETS = {
    "tl_2017_us_zcta510/tl_2017_us_zcta510",
    "Global_LSIB_Polygons_Detailed/Global_LSIB_Polygons_Detailed",
    // Natural Earth admin boundaries (auto-downloadable)
    "ne_10m_admin_0_countries/ne_10m_admin_0_countries",
    "ne_10m_admin_1_states_provinces/ne_10m_admin_1_states_provinces",
    "ne_50m_admin_0_countries/ne_50m_admin_0_countries"
};

// New CSV datasets (can be converted to HDF5)
const std::vector<std::string> CSV_DATASETS = {
    "covid19/csse_covid_19_daily_reports/*.csv",
    "gdelt/gdelt_events_sample.csv",
    "infrastructure/*.csv"
};

// ============================================================================
// Helper Functions
// ============================================================================

/**
 * Get full path to a COVID-19 dataset file
 */
inline std::string get_covid19_path(const std::string& filename) {
    return COVID19_PATH + "/" + filename;
}

/**
 * Get full path to a GDELT dataset file
 */
inline std::string get_gdelt_path(const std::string& filename) {
    return GDELT_PATH + "/" + filename;
}

/**
 * Get full path to an infrastructure dataset file
 */
inline std::string get_infrastructure_path(const std::string& filename) {
    return INFRASTRUCTURE_PATH + "/" + filename;
}

/**
 * Get full path to a shapefile dataset
 */
inline std::string get_shapefile_path(const std::string& shapefile_name) {
    return SHAPEFILES_PATH + "/" + shapefile_name;
}

/**
 * Get full path to an admin boundary shapefile
 */
inline std::string get_admin_boundary_path(const std::string& boundary_name) {
    return ADMIN_BOUNDARIES_PATH + "/" + boundary_name;
}

/**
 * Get full path to an HDF5 converted dataset
 */
inline std::string get_hdf5_path(const std::string& filename) {
    return HDF5_PATH + "/" + filename;
}

/**
 * Get path for experiment output with given name
 */
inline std::string get_experiment_output_path(const std::string& experiment_name) {
    return EXPERIMENTS_OUTPUT_PATH + "/" + experiment_name;
}

/**
 * Check if a file or directory exists
 */
inline bool path_exists(const std::string& path) {
    struct stat buffer;
    return (stat(path.c_str(), &buffer) == 0);
}

/**
 * Check if a dataset file exists
 */
inline bool dataset_exists(const std::string& path) {
    return path_exists(path);
}

/**
 * Get list of available datasets (checks downloaded datasets)
 */
inline std::vector<std::string> get_available_datasets() {
    std::vector<std::string> available;

    if (path_exists(COVID19_DAILY_REPORTS)) available.push_back("covid19");
    if (path_exists(GDELT_EVENTS_CSV)) available.push_back("gdelt");
    if (path_exists(INFRASTRUCTURE_PATH)) available.push_back("infrastructure");

    return available;
}

} // namespace dataset_config

// ============================================================================
// Backward Compatibility Aliases
// ============================================================================

// For old code that uses these global variables
const std::string experiments_path = dataset_config::EXPERIMENTS_OUTPUT_PATH;
const std::vector<std::string> polygon_sets = dataset_config::POLYGON_DATASETS;

#endif // DATASET_CONFIG_HPP
EOF

log_success "Generated dataset_config.hpp"

###############################################################################
# Verify Configuration
###############################################################################

log_info "Verifying configuration..."

# Check if datasets directory exists
if [ ! -d "$DATASETS_PATH" ]; then
    log_warning "Datasets directory does not exist: $DATASETS_PATH"
    log_info "Run ./download_datasets.sh to download datasets"
fi

# Check for downloaded datasets
DATASETS_FOUND=0

if [ -d "$DATASETS_PATH/covid19" ]; then
    log_success "Found COVID-19 dataset"
    DATASETS_FOUND=$((DATASETS_FOUND + 1))
fi

if [ -f "$DATASETS_PATH/gdelt/gdelt_events_sample.csv" ]; then
    log_success "Found GDELT dataset"
    DATASETS_FOUND=$((DATASETS_FOUND + 1))
fi

if [ -d "$DATASETS_PATH/infrastructure" ]; then
    log_success "Found infrastructure dataset"
    DATASETS_FOUND=$((DATASETS_FOUND + 1))
fi

if [ $DATASETS_FOUND -eq 0 ]; then
    log_warning "No datasets found in $DATASETS_PATH"
    echo ""
    echo "To download datasets, run:"
    echo "  ./download_datasets.sh"
    echo ""
fi

###############################################################################
# Summary
###############################################################################

echo ""
echo "╔════════════════════════════════════════════════════════════╗"
echo "║              Dataset Configuration Complete                ║"
echo "╚════════════════════════════════════════════════════════════╝"
echo ""
log_success "Configuration file updated: $CONFIG_FILE"
echo ""
echo "Next steps:"
echo "  1. Download datasets (if not already done):"
echo "     ./download_datasets.sh"
echo ""
echo "  2. Rebuild C++ experiments:"
echo "     cd build && make"
echo ""
echo "  3. Run experiments:"
echo "     ./build/test_datasets"
echo ""
echo "Dataset paths configured:"
echo "  - Datasets:        $DATASETS_PATH"
echo "  - Experiments:     $EXPERIMENTS_OUTPUT_PATH"
echo ""
